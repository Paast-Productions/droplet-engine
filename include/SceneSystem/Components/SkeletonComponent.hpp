#pragma once

#include <SceneSystem/Component.hpp>
#include <SceneSystem/Node.hpp>
#include <resource/ResourceHandle.hpp>
#include <resource/types/SkinnedMeshResource.hpp>

#include <cstddef>
#include <memory>
#include <string>
#include <string_view>
#include <vector>

namespace Droplet::Scene
{
    /// @brief Component that builds a Node hierarchy mirroring the bone structure of a SkinnedMeshResource.
    ///
    /// The generated bone Nodes are children (or deeper descendants) of the owner Node. Bones without a
    /// valid parent become direct children of the owner. The owner's space is treated as the mesh space
    /// of the skinned mesh. Bone Nodes are given their bind pose transforms.
    class SkeletonComponent : public Component
    {
    public:
        SkeletonComponent() = default;

        /// @brief Gets the type name of the component.
        /// @return The type name of the component.
        [[nodiscard]] std::string_view GetTypeName() const override { return "SkeletonComponent"; }

        /// @brief Gets the skinned mesh resource handle.
        [[nodiscard]] const ResourceHandle<SkinnedMeshResource> &GetSkinnedMeshResource() const { return m_skinnedMesh; }

        /// @brief Sets the skinned mesh resource handle. The skeleton is built if the resource is already ready; otherwise use SetSkinnedMeshGUID, which builds it from the resource's onLoad callback.
        void SetSkinnedMeshResource(ResourceHandle<SkinnedMeshResource> p_handle);

        /// @brief Sets the skinned mesh resource using its GUID.
        void SetSkinnedMeshGUID(GUID p_guid);

        /// @brief Gets the GUID of the assigned skinned mesh resource, or the invalid GUID if none is assigned.
        [[nodiscard]] GUID GetSkinnedMeshGUID() const { return m_skinnedMesh.GetGUID(); }

        /// @brief Replaces the generated bone Nodes with a hierarchy built from the given resource.
        /// @param p_mesh The skinned mesh to build from. If nullptr, the generated Nodes are removed.
        /// @note Requires the component to have an owner. Without one, nothing is built.
        void BuildSkeleton(const SkinnedMeshResource *p_mesh);

        /// @brief Removes all Nodes generated by this component.
        void ClearSkeleton();

        /// @brief Gets the generated Node for a bone.
        /// @param p_boneIndex Index of the bone in SkinnedMeshResource::GetBones().
        /// @return The bone Node, or nullptr if the index is out of range or no skeleton is built.
        [[nodiscard]] std::shared_ptr<Node> GetBoneNode(std::size_t p_boneIndex) const;

        /// @brief Gets the generated Nodes, indexed by bone index.
        [[nodiscard]] const std::vector<std::shared_ptr<Node>> &GetBoneNodes() const { return m_boneNodes; }

        /// @brief Gets the number of generated bone Nodes.
        [[nodiscard]] std::size_t GetBoneCount() const { return m_boneNodes.size(); }

    protected:
        void StartImpl() override;
        void RenderUIImpl() override;

        nlohmann::json SerializeImpl() override;
        void DeserializeImpl(nlohmann::json p_compJson) override;

    private:
        void SyncWithResource();

        /// @brief Draws bones as joints and connecting lines using DebugDraw.
        void DrawDebugSkeleton() const;

        /// @brief Liveness token so resource load callbacks do not touch a destroyed component.
        std::shared_ptr<bool> m_alive = std::make_shared<bool>(true);

        ResourceHandle<SkinnedMeshResource> m_skinnedMesh{};
        std::string m_meshDisplayName;

        /// @brief Resource the current skeleton was built from (nullptr if built manually or not built).
        const SkinnedMeshResource *m_builtFrom = nullptr;

        /// @brief Generated Nodes, indexed by bone index.
        std::vector<std::shared_ptr<Node>> m_boneNodes;
    };
}
